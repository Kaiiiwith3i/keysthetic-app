#!/usr/bin/env bash
# Runs every end-to-end flow on the emulator against a freshly seeded server and
# writes the COMPLETE raw output plus a PASS/FAIL table to ../E2E-RESULTS.md.
# E2E-RESULTS.md is generated: never edit it by hand.
#
#   integration_test/run_all.sh
#
# Needs: emulator running (adb devices -> emulator-5554), port 8080 free.
# Flows 1-9 run with the server up; the server is then STOPPED and flow 10 (demo mode) runs.

APP="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVER="$(cd "$APP/../keysthetic-server" && pwd)"
FLUTTER=/opt/homebrew/share/flutter/bin/flutter
DART=/opt/homebrew/share/flutter/bin/dart
ADB=/opt/homebrew/share/android-commandlinetools/platform-tools/adb
DEVICE=emulator-5554
OUT="$APP/E2E-RESULTS.md"
TMP="$(mktemp -d)"
RAW="$TMP/raw.log"
SERVER_LOG="$TMP/server.log"
ROWS="$TMP/rows.txt"
: > "$RAW"; : > "$ROWS"

WITH_SERVER=(register_test post_listing_test search_build_test offer_test chat_test checkout_test order_complete_test legit_check_test admin_hide_test)
NO_SERVER=(demo_mode_test)

say() { echo "$*" | tee -a "$RAW"; }

stop_server() {
  pkill -f bin/server.dart 2>/dev/null
  for _ in $(seq 1 20); do curl -s -m 1 localhost:8080/health >/dev/null 2>&1 || return 0; sleep 0.5; done
  return 1
}

trap stop_server EXIT

run_flow() {
  local name="$1" start end status
  say ""
  say "=================== integration_test/$name.dart ==================="
  start=$(date +%s)
  (cd "$APP" && "$FLUTTER" test "integration_test/$name.dart" -d "$DEVICE" --reporter expanded) 2>&1 | tee -a "$RAW"
  status=${PIPESTATUS[0]}
  end=$(date +%s)
  local verdict=FAIL
  [ "$status" -eq 0 ] && verdict=PASS
  say "--- $name: $verdict (exit $status) ---"
  echo "$name.dart|$verdict|$((end - start))" >> "$ROWS"
}

# ---------------------------------------------------------------- preflight
if ! "$ADB" devices | grep -q "^$DEVICE[[:space:]]*device"; then
  echo "Emulator $DEVICE is not running. Start: emulator -avd ks_pixel" >&2
  exit 2
fi
say "# preflight: stop any running server, reseed"
stop_server || { echo "port 8080 is still busy" >&2; exit 2; }
(cd "$SERVER" && "$DART" run bin/seed.dart) 2>&1 | tee -a "$RAW"
[ "${PIPESTATUS[0]}" -eq 0 ] || { echo "seed failed" >&2; exit 2; }

say "# starting server (log: $SERVER_LOG)"
(cd "$SERVER" && nohup "$DART" run bin/server.dart > "$SERVER_LOG" 2>&1 &)
for _ in $(seq 1 60); do curl -s -m 1 localhost:8080/health 2>/dev/null | grep -q '"ok":true' && break; sleep 1; done
if ! curl -s -m 2 localhost:8080/health | grep -q '"ok":true'; then
  echo "server did not come up; log:" >&2; cat "$SERVER_LOG" >&2; exit 2
fi
say "# /health -> $(curl -s localhost:8080/health)"

# ---------------------------------------------------------------- flows 1-9 (server up)
for f in "${WITH_SERVER[@]}"; do run_flow "$f"; done

# ---------------------------------------------------------------- flow 10 (server stopped)
say ""
say "# stopping the server for the demo-mode flow"
stop_server && say "# server is down (health check refused)" || say "# WARNING: server still answering"
for f in "${NO_SERVER[@]}"; do run_flow "$f"; done

# ---------------------------------------------------------------- report
MODEL=$("$ADB" -s "$DEVICE" shell getprop ro.product.model | tr -d '\r')
ANDROID=$("$ADB" -s "$DEVICE" shell getprop ro.build.version.release | tr -d '\r')
SDK=$("$ADB" -s "$DEVICE" shell getprop ro.build.version.sdk | tr -d '\r')
commit() { # short hash, marked when tracked files differ from it
  local h d; h=$(git -C "$1" rev-parse --short HEAD 2>/dev/null || echo unknown)
  d=$(git -C "$1" status --porcelain --untracked-files=no 2>/dev/null | wc -l | tr -d ' ')
  [ "$d" != "0" ] && h="$h (+$d modified tracked files)"
  echo "$h"
}
PASS=$(grep -c '|PASS|' "$ROWS"); TOTAL=$(wc -l < "$ROWS" | tr -d ' ')

{
  echo "# Keysthetic end-to-end results"
  echo
  echo "_Generated by \`integration_test/run_all.sh\`. Do not edit by hand._"
  echo
  echo "- Date: $(date '+%Y-%m-%d %H:%M:%S %z')"
  echo "- Device: $MODEL (Android $ANDROID, API $SDK), emulator \`$DEVICE\`"
  echo "- App commit: $(commit "$APP")"
  echo "- Server commit: $(commit "$SERVER")"
  echo "- Server data: freshly seeded (all FAKE demo data); flows 1-9 with the server up, flow 10 with it stopped"
  echo
  echo "## Raw output"
  echo
  echo '```'
  cat "$RAW"
  echo '```'
  echo
  echo "## Server log (flows 1-9)"
  echo
  echo '```'
  cat "$SERVER_LOG"
  echo '```'
  echo
  echo "## Summary: $PASS / $TOTAL flows passed"
  echo
  echo "| File | Result | Duration |"
  echo "|---|---|---|"
  while IFS='|' read -r file verdict secs; do echo "| \`integration_test/$file\` | $verdict | ${secs}s |"; done < "$ROWS"
} > "$OUT"

echo
echo "=========== SUMMARY: $PASS / $TOTAL passed ==========="
printf '%-28s %-6s %s\n' FILE RESULT DURATION
while IFS='|' read -r file verdict secs; do printf '%-28s %-6s %ss\n' "$file" "$verdict" "$secs"; done < "$ROWS"
echo "Wrote $OUT"
[ "$PASS" -eq "$TOTAL" ]
